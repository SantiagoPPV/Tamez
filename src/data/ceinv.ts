const doc = (
  id: string,
  code: ProjectDocument['code'],
  status: ProjectDocument['status'],
  date: string,
  context: ProjectDocument['context'] = {},
): ProjectDocument => ({
  id,
  code,
  version: 1,
  status,
  context,
  overrides: { fields: {}, lists: {} },
  snapshot: null,
  createdOn: date,
  sentOn: status === 'draft' ? null : date,
  signedOn: status === 'signed' ? date : null,
  notes: '',
})

